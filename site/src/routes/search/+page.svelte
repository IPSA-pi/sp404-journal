<script lang="ts">
	import { onMount } from 'svelte';
	import { base } from '$app/paths';
	import { dev } from '$app/environment';

	interface PagefindUIInstance {
		triggerSearch(term: string): void;
	}
	type PagefindUIConstructor = new (opts: Record<string, unknown>) => PagefindUIInstance;

	let status = $state<'loading' | 'ready' | 'missing'>('loading');

	function loadScript(src: string): Promise<void> {
		return new Promise((resolve, reject) => {
			const s = document.createElement('script');
			s.src = src;
			s.onload = () => resolve();
			s.onerror = () => reject(new Error(`failed to load ${src}`));
			document.head.appendChild(s);
		});
	}

	onMount(async () => {
		const css = document.createElement('link');
		css.rel = 'stylesheet';
		css.href = `${base}/pagefind/pagefind-ui.css`;
		document.head.appendChild(css);
		try {
			await loadScript(`${base}/pagefind/pagefind-ui.js`);
		} catch {
			status = 'missing';
			return;
		}
		const PagefindUI = (window as unknown as { PagefindUI: PagefindUIConstructor }).PagefindUI;
		const ui = new PagefindUI({
			element: '#search',
			baseUrl: `${base}/`,
			showSubResults: true,
			showImages: false,
			resetStyles: false,
			autofocus: true,
			translations: { placeholder: 'Search entries and topics' }
		});
		status = 'ready';
		const q = new URLSearchParams(location.search).get('q');
		if (q) ui.triggerSearch(q);
	});
</script>

<svelte:head><title>Search · SP-404MKII notes</title></svelte:head>

<div class="mx-auto max-w-3xl">
	<h1 class="mb-4 text-2xl font-bold tracking-tight">Search</h1>
	{#if status === 'missing'}
		<p class="rounded-lg border border-dashed border-zinc-300 p-6 text-zinc-500 dark:border-zinc-700">
			The search index has not been built.
			{#if dev}It is generated by <code>npm run build</code> (Pagefind); try <code>npm run build &amp;&amp; npm run preview</code>.{/if}
		</p>
	{:else if status === 'loading'}
		<p class="text-sm text-zinc-500">Loading search&hellip;</p>
	{/if}
	<div id="search" class="pagefind"></div>
</div>

